# Средний возраст для каждой группы из анкеты — для расчёта пульса.
AGE_MID = {'teen': 16, '18': 24, '30': 35, '40': 45, '50': 55, '60': 65}


def cardio_options(place, age_group):
    """Тренажёры для места тренировки; для 60+ — без ударной нагрузки."""
    return [k for k, (_, places, impact, _) in CARDIO.items()
            if place in places and not (impact and age_group == 'senior')]


def cardio_minutes(phase, goal, age_group):
    """(мин, макс, по умолчанию) минут кардио."""
    if phase == 'warmup':
        lo, hi = (10, 15) if age_group in ('mature', 'senior') else (5, 10)
    elif goal == 'fat_loss':
        lo, hi = 15, 20
    else:
        lo, hi = 5, 10
    return lo, hi, round((lo + hi) / 2)


def pulse_range(phase, goal, age):
    """Пульсовая зона (уд/мин): 220 − возраст = максимум."""
    hr_max = 220 - AGE_MID.get(age, 35)
    if phase == 'cooldown' and goal == 'fat_loss':
        lo, hi = 0.6, 0.7  # зона жиросжигания
    elif phase == 'cooldown':
        lo, hi = 0.5, 0.6
    else:
        lo, hi = 0.5, 0.65
    return round(hr_max * lo / 5) * 5, round(hr_max * hi / 5) * 5

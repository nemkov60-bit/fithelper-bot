def _place_ru(exercise_id):
    from exercise_images import EXERCISE_FRAMES, GYM
    place, _ = EXERCISE_FRAMES[exercise_id]
    return GYM_RU if place == GYM else HOME_RU


def build_prompt_ru(exercise_id, frame_index, female=False):
    description = FRAMES_RU[exercise_id][frame_index]
    style = STYLE_RU
    if 'крупный план' in description:
        style = style.replace('человек виден в полный рост, ', 'крупный план детали, ')
    person = FEMALE_PERSON_RU if female else PERSON_RU
    place = _place_ru(exercise_id)
    return f'{style}. {place[0].upper() + place[1:]}. {person[0].upper() + person[1:]}, {description}.'


def build_markdown_ru(exercises):
    from exercise_images import EXERCISE_FRAMES
    lines = ['# Промты на русском для иллюстраций упражнений', '',
             'Для каждого упражнения — минимум два кадра: исходное и конечное положение '
             '(для сложных базовых — третий кадр с ключевой деталью или типичной ошибкой).', '',
             '**Как пользоваться**', '',
             '1. Скопируй промт в генератор изображений (Шедеврум, Kandinsky, GigaChat, Midjourney, DALL·E).',
             '2. Загрузи картинку через бота: «🛠 Админ» → «🖼 Фото упражнений» → упражнение → кнопка кадра. '
             'Или отправь боту фото с подписью из заголовка кадра, например `bench 1`.',
             '3. Бот покажет картинки с подписями по кнопке «📖 Техника».', '',
             f'Единый стиль серии: `{STYLE_RU}`', '',
             f'Персонаж: `{PERSON_RU}`. Для женской версии замени его на `{FEMALE_PERSON_RU}` '
             'и загружай кнопкой «📤 Кадр N 👩» (или подписью `bench 1 f`).', '',
             'Совет: генерируй всю серию в одном чате/сессии и проси «тот же персонаж, что на предыдущей картинке» — '
             'так картинки будут похожи друг на друга. Английские промты (обычно точнее для Midjourney и DALL·E) — '
             'в `IMAGE_PROMPTS.md`.', '']
    for ex in exercises:
        if ex.id not in FRAMES_RU:
            continue
        lines += [f'## {ex.name} (`{ex.id}`)', '']
        for i, desc in enumerate(FRAMES_RU[ex.id]):
            caption = EXERCISE_FRAMES[ex.id][1][i][0]
            lines += [f'**Кадр {i + 1} — `{ex.id} {i + 1}`.** {caption}', '', '```', build_prompt_ru(ex.id, i), '```', '']
    return '\n'.join(lines)


